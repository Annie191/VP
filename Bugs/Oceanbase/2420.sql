-- Single: 返回 4（错误，IF(id, NULL, id)→NULL → XOR→NULL → COUNT(NULL)=0）
SELECT COUNT((CAST(IF(id, NULL, id) AS SIGNED)) XOR (id)) FROM vp_s WHERE 1;

-- Split: RIGHT JOIN → 返回 0（正确）
SELECT COUNT((CAST(IF(id, NULL, id) AS SIGNED)) XOR (id)) FROM (
  SELECT l.id FROM vp_l l RIGHT JOIN vp_r r ON l.id = r.id
) vp_s WHERE 1;