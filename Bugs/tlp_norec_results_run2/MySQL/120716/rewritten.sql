-- ORIGINAL SINGLE-TABLE QUERY
-- 正确基线：空表聚合，返回 NULL
SELECT MIN(EXISTS(SELECT 1 WHERE FALSE)) AS v
FROM s;

-- TLP BASE (original query with WHERE removed)
/* 正确基线：空表聚合，返回 NULL */ SELECT MIN(EXISTS(SELECT 1 WHERE FALSE)) AS v FROM s;

-- TLP UNION ALL
SELECT MIN(agg0) FROM (/* 正确基线：空表聚合，返回 NULL */ SELECT MIN(EXISTS(SELECT 1 WHERE FALSE)) AS agg0 FROM s WHERE TRUE UNION ALL /* 正确基线：空表聚合，返回 NULL */ SELECT MIN(EXISTS(SELECT 1 WHERE FALSE)) AS agg0 FROM s WHERE NOT TRUE UNION ALL /* 正确基线：空表聚合，返回 NULL */ SELECT MIN(EXISTS(SELECT 1 WHERE FALSE)) AS agg0 FROM s WHERE TRUE IS NULL) AS tlp_parts;

-- NoREC optimized
/* 正确基线：空表聚合，返回 NULL */ SELECT COUNT(*) FROM s;

-- NoREC unoptimized
/* 正确基线：空表聚合，返回 NULL */ SELECT SUM(CASE WHEN TRUE THEN 1 ELSE NULL END) FROM s;
